"""Encode the third slide at display resolution as grayscale RGB565 in flash."""
from pathlib import Path
import argparse
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('image', type=Path)
args = parser.parse_args()
source = Image.open(args.image).convert('RGB')
source.save(ROOT / 'assets/slide-3-source.png')
photo = ImageOps.pad(ImageOps.grayscale(source), (224, 300),
                     method=Image.Resampling.LANCZOS, color=0).convert('RGB')
pixels = [(r >> 3) << 11 | (g >> 2) << 5 | (b >> 3)
          for r, g, b in photo.get_flattened_data()]
header = ['#pragma once', '#include <Arduino.h>',
          '// Generated by tools/generate-slide-3.py; full-detail grayscale RGB565.',
          'constexpr uint16_t COLLAGE_WIDTH = 224;',
          'constexpr uint16_t COLLAGE_HEIGHT = 300;',
          'const uint16_t collagePixels[] PROGMEM = {']
for i in range(0, len(pixels), 16):
    header.append('  ' + ', '.join(f'0x{b:04X}' for b in pixels[i:i+16]) + ',')
header += ['};']
(ROOT / 'oled_portfolio/slide_3_photo.h').write_text('\n'.join(header) + '\n')
rgb = [((c >> 11) * 255 // 31, ((c >> 5) & 63) * 255 // 63,
        (c & 31) * 255 // 31) for c in pixels]
decoded = Image.new('RGB', photo.size)
decoded.putdata(rgb)
preview = Image.new('RGB', (240, 320))
preview.paste(decoded, (8, 10))
preview.save(ROOT / 'slide-3-preview.png')
print(f'Generated slide 3: {len(pixels) * 2} pixel bytes.')
