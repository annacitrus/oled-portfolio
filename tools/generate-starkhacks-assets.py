"""Encode a full-detail grayscale photo and small Consolas glyphs in flash."""
from pathlib import Path
import argparse
import re
from PIL import Image, ImageDraw, ImageFont, ImageOps

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument("image", type=Path)
args = parser.parse_args()
source = Image.open(args.image).convert("RGB")
(ROOT / "assets").mkdir(exist_ok=True)
source.save(ROOT / "assets/starkhacks-source.png")
# Resize once to the exact display size, then encode grayscale directly as RGB565.
photo = ImageOps.fit(source, (192, 144), method=Image.Resampling.LANCZOS)
photo = ImageOps.grayscale(photo).convert("RGB")
pixels = [(r >> 3) << 11 | (g >> 2) << 5 | (b >> 3)
          for r, g, b in photo.get_flattened_data()]
def array_lines(values, digits):
    return ["  " + ", ".join(f"0x{x:0{digits}X}" for x in values[i:i+16]) + ","
            for i in range(0, len(values), 16)]
header = ["#pragma once", "#include <Arduino.h>",
          "// Generated by tools/generate-starkhacks-assets.py; full-detail grayscale RGB565.",
          "constexpr uint16_t STARK_PHOTO_WIDTH = 192;",
          "constexpr uint16_t STARK_PHOTO_HEIGHT = 144;",
          "const uint16_t starkPhotoPixels[] PROGMEM = {"]
header += array_lines(pixels, 4) + ["};"]
(ROOT / "oled_portfolio/starkhacks_photo.h").write_text("\n".join(header) + "\n")

subtitle = ["the world's largest", "hardware hackathon"]
stats = ["2M Reel views", "3k applicants"]
characters = "".join(sorted(set("".join(subtitle + stats + ["personal account"]))))
font = ImageFont.truetype("C:/Windows/Fonts/consola.ttf", 14)
small = {}
header = ["#pragma once", "#include <Arduino.h>",
          "// Consolas, 14 pixel, monochrome; generated with the photo assets.",
          f'const char smallTerminalCharacters[] PROGMEM = "{characters}";',
          f"constexpr uint8_t SMALL_TERMINAL_GLYPH_COUNT = {len(characters)};",
          "const uint8_t smallTerminalBitmaps[][16] PROGMEM = {"]
for char in characters:
    glyph = Image.new("1", (8, 16))
    ImageDraw.Draw(glyph).text((0, 0), char, font=font, fill=1)
    small[char] = glyph
    header += ["  { " + ", ".join(f"0x{x:02X}" for x in glyph.tobytes()) + " },"]
header += ["};"]
(ROOT / "oled_portfolio/small_terminal_font.h").write_text("\n".join(header) + "\n")

# Preview the actual RGB565 palette and generated glyph bits used by the sketch.
preview = Image.new("RGB", (240, 320))
rgb = [((c >> 11) * 255 // 31, ((c >> 5) & 63) * 255 // 63,
        (c & 31) * 255 // 31) for c in pixels]
decoded = Image.new("RGB", photo.size)
decoded.putdata(rgb)
preview.paste(decoded, (24, 140))
fg = (214, 211, 214)
large_header = (ROOT / "oled_portfolio/terminal_font.h").read_text()
large_chars = re.search(r'terminalCharacters\[\].*?= "(.*?)";', large_header)[1]
large_rows = re.findall(r"\{ ([^{}]+) \},", large_header)
large = {c: Image.frombytes("1", (16, 32), bytes(int(v.strip(), 16)
         for v in row.split(","))) for c, row in zip(large_chars, large_rows)}
def text_line(text, glyphs, cell, y):
    x = (240 - (len(text) + 1) * cell) // 2
    for i, c in enumerate(text):
        preview.paste(fg, (x + i * cell, y), glyphs[c])
    return x + len(text) * cell
text_line("StarkHacks", large, 16, 28)
text_line(subtitle[0], small, 8, 78)
text_line(subtitle[1], small, 8, 98)
text_line(stats[0], small, 8, 286)
cursor_x = text_line(stats[1], small, 8, 304)
ImageDraw.Draw(preview).rectangle((cursor_x, 307, cursor_x+5, 318), fill=fg)
preview.save(ROOT / "slide-2-preview.png")
print(f"Generated photo ({len(pixels) * 2} bytes), small font, and slide-2-preview.png.")
