# Rasterize only the large characters needed by the slides into flash bitmaps.
# Run on Windows with Consolas installed. The Uno does not need the font file.
Add-Type -AssemblyName System.Drawing
$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$glyphWidth = 16
$glyphHeight = 32
# Read both large-text lines from the sketch so new titles cannot silently
# ship with the old intro-only glyph set. Preserve letter case when deduplicating.
$sketch = Get-Content (Join-Path $projectRoot 'oled_portfolio\oled_portfolio.ino') -Raw
$characters = ''
$seen = [System.Collections.Generic.HashSet[char]]::new()
foreach ($constant in @('INTRO_TEXT', 'STARK_TITLE')) {
  $match = [regex]::Match($sketch, ($constant + '\[\]\s+PROGMEM\s*=\s*"([^"]+)"'))
  if (-not $match.Success) { throw "Cannot find $constant in the sketch." }
  foreach ($character in $match.Groups[1].Value.ToCharArray()) {
    if ($seen.Add($character)) { $characters += $character }
  }
}
$font = New-Object System.Drawing.Font('Consolas', 28, [System.Drawing.FontStyle]::Regular, [System.Drawing.GraphicsUnit]::Pixel)
if ($font.Name -ne 'Consolas') { throw 'Consolas is required to generate this font.' }
$format = [System.Drawing.StringFormat]::GenericTypographic.Clone()
$format.FormatFlags = $format.FormatFlags -bor [System.Drawing.StringFormatFlags]::NoWrap
$rows = New-Object System.Collections.Generic.List[string]
$rows.Add('#pragma once')
$rows.Add('#include <avr/pgmspace.h>')
$rows.Add('// Consolas, 28 pixel, monochrome. Generated by tools/generate-terminal-font.ps1.')
$rows.Add('constexpr uint8_t TERMINAL_CELL_WIDTH = 16;')
$rows.Add('constexpr uint8_t TERMINAL_CELL_HEIGHT = 32;')
$rows.Add("constexpr uint8_t TERMINAL_GLYPH_COUNT = $($characters.Length);")
$rows.Add("const char terminalCharacters[] PROGMEM = `"$characters`";")
$rows.Add('const uint8_t terminalBitmaps[TERMINAL_GLYPH_COUNT][64] PROGMEM = {')
$glyphs = [System.Collections.Generic.Dictionary[string, System.Drawing.Bitmap]]::new([System.StringComparer]::Ordinal)
foreach ($character in $characters.ToCharArray()) {
  $bitmap = New-Object System.Drawing.Bitmap($glyphWidth, $glyphHeight)
  $graphics = [System.Drawing.Graphics]::FromImage($bitmap)
  $graphics.Clear([System.Drawing.Color]::Black)
  $graphics.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::SingleBitPerPixelGridFit
  $graphics.DrawString([string]$character, $font, [System.Drawing.Brushes]::White, [System.Drawing.PointF]::new(0, 0), $format)
  $bytes = New-Object System.Collections.Generic.List[string]
  for ($y = 0; $y -lt $glyphHeight; $y++) {
    for ($group = 0; $group -lt 2; $group++) {
      $value = 0
      for ($bit = 0; $bit -lt 8; $bit++) {
        if ($bitmap.GetPixel($group * 8 + $bit, $y).R -gt 127) {
          $value = $value -bor (1 -shl (7 - $bit))
        }
      }
      $bytes.Add(('0x{0:X2}' -f $value))
    }
  }
  $rows.Add("  { $($bytes -join ', ') }, // '$character'")
  $glyphs[[string]$character] = $bitmap
  $graphics.Dispose()
}
$rows.Add('};')
[System.IO.File]::WriteAllLines((Join-Path $projectRoot 'oled_portfolio\terminal_font.h'), $rows)

# Preview uses the same monochrome glyph pixels and cursor as the sketch.
$preview = New-Object System.Drawing.Bitmap(240, 320)
$previewGraphics = [System.Drawing.Graphics]::FromImage($preview)
$previewGraphics.Clear([System.Drawing.Color]::Black)
$name = 'Anna Citron'
$textLeft = (240 - ($name.Length + 1) * $glyphWidth) / 2
$textTop = (320 - $glyphHeight) / 2
$foreground = [System.Drawing.Color]::FromArgb(214, 211, 214)
for ($index = 0; $index -lt $name.Length; $index++) {
  $glyph = $glyphs[[string]$name[$index]]
  for ($y = 0; $y -lt $glyphHeight; $y++) {
    for ($x = 0; $x -lt $glyphWidth; $x++) {
      if ($glyph.GetPixel($x, $y).R -gt 127) {
        $preview.SetPixel($textLeft + $index * $glyphWidth + $x, $textTop + $y, $foreground)
      }
    }
  }
}
$cursorBrush = New-Object System.Drawing.SolidBrush($foreground)
$previewGraphics.FillRectangle($cursorBrush, $textLeft + $name.Length * $glyphWidth, $textTop + 5, 14, 25)
$preview.Save((Join-Path $projectRoot 'slide-1-preview.png'), [System.Drawing.Imaging.ImageFormat]::Png)
$cursorBrush.Dispose()
$previewGraphics.Dispose()
$preview.Dispose()
foreach ($glyph in $glyphs.Values) { $glyph.Dispose() }
$font.Dispose()
$format.Dispose()
Write-Output 'Generated terminal_font.h and slide-1-preview.png.'
