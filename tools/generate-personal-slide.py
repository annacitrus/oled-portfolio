"""Build the personal-account slide from the supplied four-video concept."""
from pathlib import Path
import argparse
import re
from PIL import Image, ImageDraw, ImageOps

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('image', type=Path)
parser.add_argument('--fourth-image', type=Path,
                    default=ROOT / 'assets/personal-tile-4-source.png')
args = parser.parse_args()
source = Image.open(args.image).convert('RGB')
source.save(ROOT / 'assets/personal-source.png')
fourth = Image.open(args.fourth_image).convert('RGB')
fourth.save(ROOT / 'assets/personal-tile-4-source.png')
if source.size != (462, 613):
    raise ValueError('Expected the original 462 x 613 concept screenshot.')

# Rebuild the layout instead of shrinking the screenshot's white gutters and text.
canvas = Image.new('RGB', (224, 304), 'black')
# Trim the first tile's platform badge and duplicate view-count footer.
crops = [(17, 45, 230, 273), (243, 4, 430, 294),
         (31, 338, 202, 611), (250, 338, 425, 611)]
positions = [(0, 0), (116, 0), (0, 176), (116, 176)]
for index, (bounds, position) in enumerate(zip(crops, positions)):
    tile = ImageOps.grayscale(source.crop(bounds))
    if index == 3:
        tile = ImageOps.grayscale(fourth)
    if index == 0:
        tile = tile.resize((108, 128), Image.Resampling.LANCZOS)
    else:
        tile = ImageOps.fit(tile, (108, 128), method=Image.Resampling.LANCZOS)
    canvas.paste(tile, position)

# Leave the middle band empty: firmware types both lines using the shared fonts.
pixels = [(r >> 3) << 11 | (g >> 2) << 5 | (b >> 3)
          for r, g, b in canvas.get_flattened_data()]
header = ['#pragma once', '#include <Arduino.h>',
          '// Generated by tools/generate-personal-slide.py; grayscale RGB565.',
          'constexpr uint16_t PERSONAL_WIDTH = 224;',
          'constexpr uint16_t PERSONAL_HEIGHT = 304;',
          'const uint16_t personalPixels[] PROGMEM = {']
for i in range(0, len(pixels), 16):
    header.append('  ' + ', '.join(f'0x{v:04X}' for v in pixels[i:i+16]) + ',')
header.append('};')
(ROOT / 'oled_portfolio/personal_photo.h').write_text('\n'.join(header) + '\n')
decoded = Image.new('RGB', canvas.size)
decoded.putdata([((c >> 11) * 255 // 31, ((c >> 5) & 63) * 255 // 63,
                  (c & 31) * 255 // 31) for c in pixels])
preview = Image.new('RGB', (240, 320))
preview.paste(decoded, (8, 8))
# Final typed frame, using exactly the same glyph bits and coordinates as firmware.
sketch = (ROOT / 'oled_portfolio/oled_portfolio.ino').read_text()
for constant, filename, prefix, cell, height, y in [
        ('PERSONAL_USERNAME', 'terminal_font.h', 'terminal', 16, 32, 136),
        ('PERSONAL_LABEL', 'small_terminal_font.h', 'smallTerminal', 8, 16, 168)]:
    text = re.search(constant + r'\[\].*?= "(.*?)";', sketch)[1]
    font_header = (ROOT / 'oled_portfolio' / filename).read_text()
    chars = re.search(prefix + r'Characters\[\].*?= "(.*?)";', font_header)[1]
    rows = re.findall(r'\{ ([^{}]+) \},', font_header)
    glyphs = {c: Image.frombytes('1', (cell, height), bytes(
        int(v.strip(), 16) for v in row.split(',')))
        for c, row in zip(chars, rows)}
    x = (240 - (len(text) + 1) * cell) // 2
    for i, char in enumerate(text):
        preview.paste((214, 211, 214), (x + i * cell, y), glyphs[char])
ImageDraw.Draw(preview).rectangle(
    (x + len(text) * cell, y + 3, x + len(text) * cell + 5, y + 14),
    fill=(214, 211, 214))
preview.save(ROOT / 'slide-4-preview.png')
print(f'Generated personal slide: {len(pixels) * 2} pixel bytes.')
